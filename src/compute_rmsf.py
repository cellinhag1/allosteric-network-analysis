#!/usr/bin/env python
"""
Per-residue (CA) RMSF for the completed 1us restrained ME1 MD runs, from the
water-stripped, imaging-corrected pbc_fixed/ trajectories.

Method: stream through every frame (all 10 segments in order), rigid-body
superpose the protein's CA atoms onto a single reference frame (t=0 of this
replicate) using the Kabsch algorithm, then accumulate running sum and
sum-of-squares of the aligned CA positions. RMSF per residue is computed
from those running totals at the end (no need to hold all frames in memory
at once):

    mean_pos[i]      = sum_pos[i] / n_frames
    var[i]           = sum_sq[i]/n_frames - mean_pos[i]**2      (per x,y,z)
    RMSF[i]           = sqrt( var[i].sum() )                     (per residue)

This is the standard per-residue root-mean-square-fluctuation about the
time-averaged (aligned) position, isolating internal flexibility from the
protein's overall translation/rotation (which the imaging fix intentionally
leaves alone, since removing it there would have discarded real motion --
alignment here is what removes it for the purposes of RMSF specifically).

For with_inhibitor, frames are additionally restricted to those where LIGAND is
actually bound in the pocket (inhib_pocket_dist <= BOUND_CUTOFF, same 10A
cutoff already used in compute_openclosed_metrics.py / summarize_openclosed_
metrics.py -- kept in memory now for consistency, not that it excludes much:
~0.12% of frames). This avoids letting the rare excursion frames leak into
what's supposed to be a read on the "inhibitor-bound, locked-open" state.

Usage:
    python compute_rmsf.py <system> <rep>
    system : with_inhibitor | no_inhibitor
    rep    : 0-4
"""
import sys
import os
import numpy as np
import pandas as pd
import MDAnalysis as mda
from MDAnalysis.analysis.align import rotation_matrix

system = sys.argv[1].lower()
rep    = int(sys.argv[2])

from config import DYN
FIXED   = f"{DYN}/pbc_fixed"
ALLOST  = f"{BASE}/allostery"
OUT     = f"{ALLOST}/rmsf"
os.makedirs(OUT, exist_ok=True)

BOUND_CUTOFF = 10.0   # Angstrom, LIGAND COM <-> pocket-CA centroid

if system == 'with_inhibitor':
    PREFIX = 'me1_239_malate_restrained'
elif system == 'no_inhibitor':
    PREFIX = 'me1_malate_noinhibit_restrained'
else:
    sys.exit(f"Unknown system '{system}' -- expected with_inhibitor or no_inhibitor")

PSF = f"{FIXED}/{PREFIX}_complex.psf"
SEGMENTS = [(i * 100, (i + 1) * 100) for i in range(10)]
OUT_NPZ = f"{OUT}/{PREFIX}_{rep}_rmsf.npz"

if os.path.isfile(OUT_NPZ):
    print(f"EXISTS, skipping: {OUT_NPZ}")
    sys.exit(0)

print(f"System: {system}  Replicate: {rep}", flush=True)

# Bound-frame mask (with_inhibitor only) -- built from the already-computed
# inhib_pocket_dist column in compute_openclosed_metrics.py's output, which
# was generated by iterating frames in the exact same segment order used
# here, so row i there == frame i here.
bound_mask = None
n_excluded = 0
if system == 'with_inhibitor':
    metrics_csv = f"{ALLOST}/openclosed_metrics/{PREFIX}_{rep}_metrics.csv"
    if not os.path.isfile(metrics_csv):
        sys.exit(f"Need {metrics_csv} (run compute_openclosed_metrics.py first) "
                  f"to build the inhibitor-bound frame filter.")
    mdf = pd.read_csv(metrics_csv)
    bound_mask = (mdf['inhib_pocket_dist'] <= BOUND_CUTOFF).values
    n_excluded = int((~bound_mask).sum())
    print(f"Inhibitor-bound filter: {bound_mask.sum()}/{len(bound_mask)} frames "
          f"bound (<= {BOUND_CUTOFF}A), excluding {n_excluded}", flush=True)

u = mda.Universe(PSF)
ca = u.select_atoms('segid PROA and name CA')
resids = ca.resids.copy()
n_res = len(ca)
print(f"CA atoms (residues): {n_res}", flush=True)

sum_pos = np.zeros((n_res, 3))
sum_sq  = np.zeros((n_res, 3))
n_frames_total = 0
n_skipped = 0
global_frame_idx = 0
ref_ca = None   # reference CA positions (centered), set from the first INCLUDED frame

for (start, end) in SEGMENTS:
    dcd = f"{FIXED}/{PREFIX}_{rep}_{start}to{end}ns_fixed.dcd"
    if not os.path.isfile(dcd):
        print(f"  SKIP (missing): {dcd}", flush=True)
        continue

    print(f"Processing {start}-{end} ns ...", flush=True)
    u.load_new(dcd)
    n_frames = len(u.trajectory)

    for iframe, ts in enumerate(u.trajectory):
        if bound_mask is not None and not bound_mask[global_frame_idx]:
            n_skipped += 1
            global_frame_idx += 1
            continue

        mobile = ca.positions.copy()
        mobile_center = mobile.mean(axis=0)
        mobile_centered = mobile - mobile_center

        if ref_ca is None:
            ref_ca = mobile_centered.copy()
            aligned = mobile_centered   # first included frame defines the reference
        else:
            R, _rmsd = rotation_matrix(mobile_centered, ref_ca)
            aligned = mobile_centered @ R.T

        sum_pos += aligned
        sum_sq  += aligned ** 2
        n_frames_total += 1
        global_frame_idx += 1

        if (iframe + 1) % 5000 == 0:
            print(f"  Frame {iframe + 1}/{n_frames}", flush=True)

print(f"Total frames: {n_frames_total}", flush=True)

mean_pos = sum_pos / n_frames_total
var = sum_sq / n_frames_total - mean_pos ** 2
var = np.clip(var, 0, None)   # guard against tiny negative values from fp roundoff
rmsf = np.sqrt(var.sum(axis=1))

if bound_mask is not None:
    assert global_frame_idx == len(bound_mask), \
        f"Frame count mismatch: processed {global_frame_idx}, mask has {len(bound_mask)}"
    assert n_skipped == n_excluded, f"n_skipped={n_skipped} != n_excluded={n_excluded}"
    print(f"Skipped {n_skipped} unbound frames, used {n_frames_total} bound frames.", flush=True)

np.savez(OUT_NPZ, resids=resids, rmsf=rmsf, n_frames=n_frames_total, n_skipped=n_skipped)
print(f"Wrote -> {OUT_NPZ}", flush=True)
